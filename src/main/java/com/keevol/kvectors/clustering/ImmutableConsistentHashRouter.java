public class ImmutableConsistentHashRouter<T> {

    private final ConsistentHashRouter<T> router;

    public ImmutableConsistentHashRouter(Collection<T> initialNodes, HashFunction hashFunction) {
        router = new ConsistentHashRouter<>(initialNodes, hashFunction, 1);
    }

    public T getNode(String key) {
        return router.getNode(key);
    }
}
